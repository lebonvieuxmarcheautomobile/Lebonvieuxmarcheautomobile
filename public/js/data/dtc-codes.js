/** Description d'un code : précise si connue, sinon déduite de la structure du code. */
export function describeDtc(code) {
  const known = DTC[code];
  if (known) return { code, text: known[0], severity: known[1], generic: true };
  const fam = FAMILY[code[0]] || 'Inconnu';
  const manufacturer = code[1] === '1' || code[1] === '3';
  const sub = code[0] === 'P' ? SUBSYSTEM[code[2]] : undefined;
  return {
    code,
    text: `${fam}${sub ? ' — ' + sub : ''}${manufacturer ? ' (code spécifique constructeur)' : ''}`,
    severity: code[0] === 'B' && /^B00/.test(code) ? 3 : 2, // B00xx = airbags
    generic: false,
  };
}
